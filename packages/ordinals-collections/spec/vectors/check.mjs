// The schema uses only these standard JSON Schema 2020-12 keywords. No Ajv/runtime dependency.
function validate(s, v, path = "$") {
  if (s.$ref) {
    const target = s.$ref
      .split("/")
      .slice(1)
      .reduce((x, k) => x[k], schema);
    return validate(target, v, path);
  }
  const type = (t) =>
    t === "null"
      ? v === null
      : t === "array"
        ? Array.isArray(v)
        : t === "object"
          ? v !== null && typeof v === "object" && !Array.isArray(v)
          : t === "integer"
            ? Number.isSafeInteger(v)
            : typeof v === t;
  if (s.type)
    assert(
      (Array.isArray(s.type) ? s.type : [s.type]).some(type),
      path + ": type",
    );
  if ("const" in s) assert.deepEqual(v, s.const, path + ": const");
  if (s.enum) assert(s.enum.includes(v), path + ": enum");
  if (typeof v === "string" && s.pattern)
    assert(new RegExp(s.pattern).test(v), path + ": pattern");
  if (typeof v === "number") {
    if (s.minimum !== undefined) assert(v >= s.minimum, path + ": minimum");
    if (s.maximum !== undefined) assert(v <= s.maximum, path + ": maximum");
  }
  if (Array.isArray(v)) {
    if (s.minItems !== undefined)
      assert(v.length >= s.minItems, path + ": minItems");
    if (s.uniqueItems)
      assert.equal(
        new Set(v.map(JSON.stringify)).size,
        v.length,
        path + ": unique",
      );
    if (s.items)
      v.forEach((x, i) => validate(s.items, x, path + "[" + i + "]"));
  } else if (v !== null && typeof v === "object") {
    for (const k of s.required || [])
      assert(Object.hasOwn(v, k), path + ": required " + k);
    if (s.additionalProperties === false)
      for (const k of Object.keys(v))
        assert(Object.hasOwn(s.properties || {}, k), path + ": extra " + k);
    for (const [k, sub] of Object.entries(s.properties || {}))
      if (Object.hasOwn(v, k)) validate(sub, v[k], path + "." + k);
  }
  for (const sub of s.allOf || []) validate(sub, v, path);
  if (s.if) {
    let matches = true;
    try {
      validate(s.if, v, path);
    } catch {
      matches = false;
    }
    if (matches && s.then) validate(s.then, v, path);
    if (!matches && s.else) validate(s.else, v, path);
  }
}
