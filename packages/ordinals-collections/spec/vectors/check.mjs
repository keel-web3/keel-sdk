// Decode the Bech32m independently and reconstruct each Taproot control path.
function decodeAddress(s) {
  assert(s.startsWith("tb1p"));
  const chars = "qpzry9x8gf2tvdw0s3jn54khce6mua7l",
    values = [...s.slice(3)].map((c) => chars.indexOf(c));
  assert(values.every((v) => v >= 0));
  let chk = 1;
  for (const v of [3, 3, 0, 20, 2, ...values]) {
    const high = chk >>> 25;
    chk = ((chk & 0x1ffffff) << 5) ^ v;
    [0x3b6a57b2, 0x26508e6d, 0x1ea119fa, 0x3d4233dd, 0x2a1462b3].forEach(
      (g, i) => {
        if ((high >>> i) & 1) chk ^= g;
      },
    );
  }
  assert.equal(chk >>> 0, 0x2bc830a3);
  const data = values.slice(1, -6);
  let bits = 0,
    acc = 0,
    out = [];
  for (const v of data) {
    acc = (acc << 5) | v;
    bits += 5;
    if (bits >= 8) {
      bits -= 8;
      out.push((acc >>> bits) & 255);
    }
  }
  assert(bits < 5);
  assert.equal(acc & ((1 << bits) - 1), 0);
  return Buffer.from(out).toString("hex");
}
