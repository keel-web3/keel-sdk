#!/usr/bin/env node
// Renders the SDK's EVM/Tezos capability map as the contracts review's CAPABILITY_MAP.md.
// Usage: node scripts/render-chain-capability-map.mjs --output <file> [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

import { KEEL_CHAIN_CAPABILITIES, summarizeKeelChainCapabilities } from "../packages/sdk/dist/chain-capability-map.js";

const flags = process.argv.slice(2);
const index = flags.indexOf("--output");
if (index < 0 || !flags[index + 1]) throw new Error("--output <file> is required.");
const target = resolve(flags[index + 1]);

const cell = (value) => String(value).replaceAll("|", "\\|").replaceAll("\n", " ");
const adapter = (entry) => (entry === null ? "—" : `${entry.contracts.map((name) => `\`${name}\``).join(", ")}: ${entry.behaviour}`);
const difference = (entry) => (entry.userVisibleDifference === false ? "No" : `Yes: ${entry.userVisibleDifference}`);
const notes = (entry) =>
  [
    entry.closest ? `Closest: ${entry.closest.behaviour} (${entry.closest.reason})` : "",
    entry.open ? `Open: ${entry.open}` : "",
    entry.ownerDecision ? `Owner decision: ${entry.ownerDecision}` : "",
  ]
    .filter(Boolean)
    .join(" ");

const counts = summarizeKeelChainCapabilities();
const lines = [
  "# EVM / Tezos capability map",
  "",
  "<!-- Generated by keel-sdk scripts/render-chain-capability-map.mjs from packages/sdk/src/chain-capability-map.ts. -->",
  "",
  "Owner rule: both chains behave as close to one another as possible; for Studio or",
  "the user it works the same. Each row is one Studio/SDK call with its EVM and Tezos",
  "adapters. Where a chain cannot do something, the SDK's `resolveKeelChainCapability`",
  "returns `KEEL_CHAIN_CAPABILITY_UNSUPPORTED` with the closest secure behaviour and",
  "the reason. This maps reviewed contract source; it is not a deployment or readiness claim.",
  "",
  `| Status | Count |`,
  `| --- | --- |`,
  ...Object.entries(counts).map(([status, count]) => `| ${status} | ${count} |`),
  "",
  "| Capability | Studio/SDK call | EVM adapter | Tezos adapter | Difference visible to user? | Status | Notes |",
  "| --- | --- | --- | --- | --- | --- | --- |",
  ...KEEL_CHAIN_CAPABILITIES.map((entry) =>
    `| \`${entry.id}\` | ${cell(entry.studioCall)} | ${cell(adapter(entry.evm))} | ${cell(adapter(entry.tezos))} | ${cell(difference(entry))} | ${entry.status} | ${cell(notes(entry))} |`,
  ),
  "",
];
const text = lines.join("\n");

if (flags.includes("--check")) {
  if (readFileSync(target, "utf8") !== text) {
    console.error(`${target} is stale; rerun without --check.`);
    process.exit(1);
  }
  console.log(`${KEEL_CHAIN_CAPABILITIES.length} capabilities: verified ${target}`);
} else {
  writeFileSync(target, text);
  console.log(`${KEEL_CHAIN_CAPABILITIES.length} capabilities: wrote ${target}`);
}
